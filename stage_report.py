def cmd_seg_table(cfg, summary: str | None, out: str):
    summary_path = (
        Path(summary)
        if summary
        else Path(cfg["paths"]["output_root"]) / "stage_a" / "sweep_summary.json"
    )
    if not summary_path.exists():
        raise SystemExit(f"Missing {summary_path}")

    rows = json.loads(summary_path.read_text(encoding="utf-8"))
    labels = list(cfg.get("part_labels") or [])
    show = labels if labels else ["background", "part1", "part2", "part3"]

    # Both IoU definitions, always. They are not interchangeable and the
    # difference is large: macro mIoU averages per-class IoU (so CUB's rare
    # legs/eyes count as much as background), while `dataset_iou` is smp's
    # reduction="micro" -- pooled over all pixels, hence background-dominated,
    # and the one prior work reports. On CUB the same checkpoint scores 0.5610
    # macro and 0.8978 micro. Emitting only the macro number made the Stage A
    # table read as a 40-point regression against a paper that had simply
    # measured something else.
    header = (
        "| arch | encoder | backend | val mIoU | test mIoU | "
        "val datasetIoU | test datasetIoU | "
        + " | ".join(f"val {l}" for l in show)
        + " | "
        + " | ".join(f"test {l}" for l in show)
        + " |"
    )
    sep = "|---|---|---|---:|---:|---:|---:|" + "|".join(["---:"] * (2 * len(show))) + "|"
    lines = [header, sep]
    for r in rows:
        vp = r.get("val_per_part_iou") or {}
        tp = r.get("test_per_part_iou") or {}

        def g(d, k):
            v = d.get(k)
            return f"{v:.4f}" if isinstance(v, (int, float)) else ""

        def f(x):
            return f"{x:.4f}" if isinstance(x, (int, float)) else ""

        cells = [
            str(r.get("arch", "")),
            str(r.get("encoder", "")),
            str(r.get("backend", "")),
            f(r.get("val_miou")),
            f(r.get("test_miou")),
            f(r.get("val_dataset_iou")),
            f(r.get("test_dataset_iou")),
        ]
        for lab in show:
            cells.append(g(vp, lab))
        for lab in show:
            cells.append(g(tp, lab))
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    lines.append(
        "mIoU is the macro mean of per-class IoU (`reduction=\"none\"`, then "
        "`nanmean`). datasetIoU is smp's `reduction=\"micro\"`, pooled over all "
        "pixels and therefore background-dominated; it is reported because "
        "prior work (Choton et al., 2026) uses that definition, and the two are "
        "not comparable to each other."
    )
    md = "\n".join(lines) + "\n"
    out_path = Path(out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(md, encoding="utf-8")
    print(md)
    print(f"Wrote {out_path}")


PROVENANCE_EQUIVALENCE_PATH = Path(__file__).resolve().parent / "provenance_equivalence.yaml"


def _load_equivalences(dataset: str | None, path: Path | None = None) -> list[dict]:
    """Declared-equivalent `code_version` stamps for `dataset`.

    See provenance_equivalence.yaml. Returns [] when the file is absent, so a
    checkout without one behaves exactly as before this existed.
    """
    path = path or PROVENANCE_EQUIVALENCE_PATH
    if dataset is None or not Path(path).is_file():
        return []
    import yaml

    doc = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}
    return [
        e for e in (doc.get("equivalences") or [])
        if e.get("dataset") == dataset and e.get("stamps")
    ]


def _apply_equivalences(df, equivalences: list[dict]):
    """Collapse each declared group of stamps to its `canonical` value.

    Returns (frame, notes). The frame is a copy -- the summary CSV on disk keeps
    the stamps the runs actually recorded, because the declaration is a
    judgement ABOUT that record and must not overwrite it.
    """
    notes = []
    if not equivalences or "code_version" not in df.columns:
        return df, notes
    df = df.copy()
    for entry in equivalences:
        stamps = [str(x) for x in entry["stamps"]]
        canonical = str(entry.get("canonical") or stamps[0])
        hit = df["code_version"].astype(str).isin(stamps)
        if not hit.any():
            continue
        df.loc[hit, "code_version"] = canonical
        notes.append(
            f"{int(hit.sum())} row(s) had their code_version collapsed to "
            f"`{canonical}` under the equivalence declared "
            f"{entry.get('declared', 'undated')} in "
            f"{PROVENANCE_EQUIVALENCE_PATH.name}: "
            + " ".join(str(entry.get("reason", "")).split())
        )
    return df, notes


def _enforce_single_provenance(df, allow_mixed: bool, equivalences: list[dict] | None = None):
    """Refuse to aggregate rows produced by different code.

    A comparison table is only a comparison if every cell was computed the same
    way. In August 2026 this table averaged rows from before and after the
    descriptor z-scoring fix: pre-fix, the fusion head's LayerNorm was dominated
    by raw `*_area` columns and the visual branch reached the classifier as a
    near-constant, so `concat` reproduced `descriptors_only` seed for seed.
    Those rows sat in the same table as post-fix rows with nothing to
    distinguish them, and the published table mixed both for five days.

    Two independent stamps are checked. `desc_standardized` is the specific
    marker that fix introduced; the code stamp is the general one and catches
    every future change of the same shape. The code stamp is `source_digest`
    (a content hash of the modules and config that determine a number) when
    every row carries one, falling back to `code_version` for rows written
    before digests existed.
    """
    problems = []
    df, equivalence_notes = _apply_equivalences(df, equivalences or [])
    for note in equivalence_notes:
        print(f"[ablation_table] {note}")
    if "desc_standardized" in df.columns:
        desc_modes = {"concat", "gated_residual", "attention_parts", "descriptors_only"}
        affected = df[df["mode"].isin(desc_modes)] if "mode" in df.columns else df
        stale = affected[affected["desc_standardized"] != True]  # noqa: E712
        if len(stale):
            problems.append(
                f"{len(stale)} descriptor-arm row(s) lack desc_standardized=True, "
                "i.e. they predate the descriptor z-scoring fix and are not "
                "comparable to rows that carry it."
            )
    # `source_digest` is authoritative when every row carries one: it hashes the
    # contents of the modules and config that determine a number, so it is
    # unchanged by a commit that edits no file and differs between two working
    # trees that git would both label `-dirty`. `code_version` is the fallback
    # for rows written before digests existed, and it is only a proxy -- see
    # config.code_version for the two ways it misreports.
    have_digest = "source_digest" in df.columns and not df["source_digest"].isna().any()
    stamp_col = "source_digest" if have_digest else "code_version"
    if stamp_col in df.columns:
        versions = sorted(str(v) for v in df[stamp_col].dropna().unique())
        if len(versions) > 1:
            problems.append(f"rows span {len(versions)} code versions ({stamp_col}): {versions}")
        if df[stamp_col].isna().any():
            problems.append(
                f"{int(df[stamp_col].isna().sum())} row(s) carry no {stamp_col} "
                "(written before provenance stamping)."
            )
    if not problems:
        return df, equivalence_notes
    msg = "[ablation_table] mixed provenance:\n  - " + "\n  - ".join(problems)
    if not allow_mixed:
        raise SystemExit(
            msg
            + "\n\nRe-run the affected cells, or pass --allow_mixed to build the "
            "table anyway (the result is not a controlled comparison)."
        )
    print(msg + "\n[ablation_table] --allow_mixed set; continuing.")
    return df, equivalence_notes + [
        "Built with --allow_mixed over the objection above; this table is NOT a "
        "controlled comparison. " + " ".join(msg.split())
    ]


def cmd_ablation_table(
    fusion_summary: str,
    out: str,
    reference_mode: str = "concat",
    n_boot: int = 2000,
    allow_mixed: bool = False,
    dataset: str | None = None,
):
    """Aggregate the per-seed fusion_ablation_summary.csv into a comparison
    table with bootstrap 95% CIs and, when >1 seed is present, a paired
    significance test of every arm against `reference_mode` (default:
    concatenation, the simplest deep-fusion arm) within each (group,
    mask_source) cell. With a single seed, only point estimates are shown —
    the CI/p-value columns are left blank rather than fabricated.
    """
    from metrics import bootstrap_ci, paired_bootstrap_test

    df = pd.read_csv(fusion_summary)
    df, provenance_notes = _enforce_single_provenance(
        df, allow_mixed, _load_equivalences(dataset)
    )
    group_cols = [c for c in ["mode", "group", "mask_source", "backbone"] if c in df.columns]

    # Stage B writes "n/a" for the group / mask_source of arms that have
    # neither (baseline, capacity_matched, heavy_aug, multitask). "n/a" is in
    # pandas' default NA list, so it round-trips out of the CSV as NaN -- and
    # `groupby` drops NaN keys by default. That silently deleted every
    # non-fusion arm from this table, including the whole-image reference that
    # every other arm is supposed to be compared against: 10 rows in, 2 rows
    # out. Restore the sentinel before grouping.
    for col in group_cols:
        df[col] = df[col].fillna("n/a")

    has_seed = "seed" in df.columns and df["seed"].nunique() > 1

    rows = []
    for keys, g in df.groupby(group_cols):
        keys = keys if isinstance(keys, tuple) else (keys,)
        row = dict(zip(group_cols, keys))
        for metric in ["top1", "top3", "macro_f1"]:
            if metric not in g.columns:
                continue
            ci = bootstrap_ci(g[metric].to_numpy(), n_boot=n_boot)
            row[f"{metric}_mean"] = round(ci["mean"], 4)
            row[f"{metric}_ci95"] = (
                f"[{ci['lo']:.4f}, {ci['hi']:.4f}]" if has_seed and ci["n"] > 1 else ""
            )
        row["n_seeds"] = int(g["seed"].nunique()) if "seed" in g.columns else 1
        for extra in ["n_params", "backbone_passes_per_image"]:
            if extra in g.columns:
                row[extra] = g[extra].iloc[0]
        rows.append(row)
    out_df = pd.DataFrame(rows)

    if has_seed and "mode" in df.columns and reference_mode in df["mode"].unique():
        sig_col = []
        for _, row in out_df.iterrows():
            other_keys = {c: row[c] for c in group_cols if c != "mode"}
            ref_mask = (df["mode"] == reference_mode)
            for c, v in other_keys.items():
                ref_mask &= df[c] == v
            arm_mask = df["mode"] == row["mode"]
            for c, v in other_keys.items():
                arm_mask &= df[c] == v
            if row["mode"] == reference_mode or ref_mask.sum() < 2 or arm_mask.sum() < 2:
                sig_col.append("")
                continue
            # Pair by seed identity, not row position: if a middle seed failed
            # for only one of the two arms, positional truncation would
            # silently compare mismatched seeds (e.g. arm's seed=77 vs.
            # reference's seed=42). An inner merge on `seed` keeps only the
            # seeds both arms actually share.
            arm_seeds = df.loc[arm_mask, ["seed", "top1"]].drop_duplicates("seed", keep="last")
            ref_seeds = df.loc[ref_mask, ["seed", "top1"]].drop_duplicates("seed", keep="last")
            paired = arm_seeds.merge(ref_seeds, on="seed", suffixes=("_arm", "_ref"))
            if len(paired) < 2:
                sig_col.append("")
                continue
            if set(arm_seeds["seed"]) != set(ref_seeds["seed"]):
                print(
                    f"[ablation_table] WARNING: {row['mode']} vs {reference_mode} "
                    f"({dict(other_keys)}) share only {len(paired)} seed(s) after "
                    f"matching by seed id; dropped mismatched/missing seeds."
                )
            test = paired_bootstrap_test(
                paired["top1_arm"].to_numpy(), paired["top1_ref"].to_numpy(), n_boot=n_boot
            )
            sig_col.append(f"p={test['p_value']:.3f}{'*' if test['significant_at_0.05'] else ''}")
        out_df[f"top1_vs_{reference_mode}"] = sig_col

    try:
        md = out_df.to_markdown(index=False)
    except ImportError:
        md = out_df.to_string(index=False)
    # Any provenance judgement that let this table be built travels WITH the
    # table. A rationale that lives only in a config file and a terminal
    # scrollback is one that a reader of the published numbers never sees.
    if provenance_notes:
        md += "\n\nProvenance\n" + "\n".join(f"- {n}" for n in provenance_notes)
    out_path = Path(out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(md + "\n", encoding="utf-8")
    csv_path = out_path.with_suffix(".csv")
    # The markdown keeps the human-readable "n/a", but the CSV must not: "n/a" is
    # in pandas' default NA list, so a downstream `pd.read_csv` turns it straight
    # back into NaN and any `groupby` on these columns silently drops every
    # non-fusion arm -- the exact failure documented and fixed on the way *in*
    # above, reintroduced on the way out. "none" round-trips as a plain string.
    out_df.replace({c: {"n/a": "none"} for c in group_cols}).to_csv(csv_path, index=False)
    print(md)
    print(f"Wrote {out_path} and {csv_path}")


