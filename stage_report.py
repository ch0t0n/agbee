def _read_ablation_csvs(paths):
    """Load one or more per-dataset ablation_table.csv into a single frame."""
    frames = []
    for p in paths:
        path = Path(p)
        if not path.is_file():
            print(f"[pooled] skipping missing {path}")
            continue
        df = pd.read_csv(path, keep_default_na=False)
        # `dataset` is not a column of the per-dataset table; recover it from
        # the path (outputs/{dataset}/stage_e/ablation_table.csv).
        parts = path.resolve().parts
        ds = parts[parts.index("outputs") + 1] if "outputs" in parts else path.stem
        df["dataset"] = ds
        frames.append(df)
    if not frames:
        raise SystemExit("No ablation_table.csv found; run `ablation_table` first.")
    return pd.concat(frames, ignore_index=True)


def cmd_pooled_table(inputs: list[str], out: str, metric: str = "top1_mean"):
    """Cross-dataset view: one row per (arm, descriptor group), one column per
    dataset, plus the mean rank across datasets.

    Rank, not raw accuracy, is the pooled summary. Averaging top-1 across
    Beemachine (160 classes), CUB (199) and Fish-Vista (1,758) would be
    meaningless -- the numbers are not on a common scale and the mean would be
    dominated by whichever corpus happens to be easiest. Mean rank answers the
    question the plan actually asks (H1: is there a universal winner?) and is
    invariant to that.
    """
    df = _read_ablation_csvs(inputs)
    if metric not in df.columns:
        raise SystemExit(f"{metric} not in {sorted(df.columns)}")
    keys = [c for c in ("mode", "group") if c in df.columns]
    # One number per (dataset, arm, group): the best cell across mask sources
    # and backbones, i.e. each arm shown at its own best configuration.
    best = df.groupby(["dataset"] + keys)[metric].max().reset_index()
    best["rank"] = best.groupby("dataset")[metric].rank(ascending=False, method="min")

    wide = best.pivot_table(index=keys, columns="dataset", values=metric)
    ranks = best.pivot_table(index=keys, columns="dataset", values="rank")
    wide["mean_rank"] = ranks.mean(axis=1).round(2)
    wide["n_datasets"] = ranks.notna().sum(axis=1)
    wide = wide.sort_values("mean_rank").round(4).reset_index()

    out_path = Path(out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    wide.to_csv(out_path.with_suffix(".csv"), index=False)
    try:
        md = wide.to_markdown(index=False)
    except ImportError:
        md = wide.to_string(index=False)
    note = (
        f"\nCells are the best {metric} for that arm on that dataset, across mask "
        "sources and backbones. `mean_rank` averages within-dataset ranks and is "
        "the pooled summary: raw accuracy is not comparable across corpora with "
        "160 / 199 / 1,758 classes.\n"
    )
    out_path.write_text(md + "\n" + note, encoding="utf-8")
    print(md + note)
    print(f"Wrote {out_path} and {out_path.with_suffix('.csv')}")


def cmd_recommend(inputs: list[str], out: str, reference_mode: str = "baseline"):
    """The mechanism-by-constraint recommendation table (research plan Sec. 7).

    Deliberately mechanical: for each operating constraint it selects the arm
    that maximises the relevant metric among the arms that satisfy the
    constraint, and reports the margin over the whole-image reference. If the
    best arm under a constraint is the reference itself, that is what gets
    recommended -- the plan's stated risk is that a "no clear winner" result
    reads as a weak paper, and the mitigation is to report it plainly.
    """
    df = _read_ablation_csvs(inputs)
    metric = "top1_mean"
    if metric not in df.columns:
        raise SystemExit(f"{metric} not in {sorted(df.columns)}")

    def profile(mode):
        return ARM_PROFILE.get(str(mode), {"passes": "?", "needs_mask": None, "needs_desc": None})

    def single_pass(mode):
        return profile(mode)["passes"] == 1

    def maskless(mode):
        return profile(mode)["needs_mask"] is False

    constraints = [
        ("No constraint", lambda m: True),
        ("Compute-constrained (1 backbone pass/image)", single_pass),
        ("No segmenter available at serving time", maskless),
        ("Masks unreliable (predicted/pseudo only)", lambda m: True),
    ]

    rows = []
    for ds, g in df.groupby("dataset"):
        ref = g[g["mode"] == reference_mode][metric]
        ref_val = float(ref.max()) if len(ref) else float("nan")
        for label, ok in constraints:
            sub = g[g["mode"].map(ok)]
            if label.startswith("Masks unreliable") and "mask_source" in g.columns:
                sub = sub[sub["mask_source"].isin(["pred", "pseudo", "n/a", "none"])]
            if not len(sub):
                continue
            best = sub.loc[sub[metric].idxmax()]
            rows.append(
                {
                    "dataset": ds,
                    "constraint": label,
                    "recommended_arm": best["mode"],
                    "descriptor_group": best.get("group", ""),
                    "mask_source": best.get("mask_source", ""),
                    "top1": round(float(best[metric]), 4),
                    "vs_reference": round(float(best[metric]) - ref_val, 4),
                    "passes_per_image": profile(best["mode"])["passes"],
                }
            )
    out_df = pd.DataFrame(rows)
    out_path = Path(out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_df.to_csv(out_path.with_suffix(".csv"), index=False)
    try:
        md = out_df.to_markdown(index=False)
    except ImportError:
        md = out_df.to_string(index=False)
    note = (
        f"\n`vs_reference` is the top-1 margin over the `{reference_mode}` arm on the "
        "same dataset. A non-positive margin means no arm satisfying that constraint "
        "beat the whole-image reference, which is a result, not a gap in the table.\n"
    )
    out_path.write_text(md + "\n" + note, encoding="utf-8")
    print(md + note)
    print(f"Wrote {out_path} and {out_path.with_suffix('.csv')}")


